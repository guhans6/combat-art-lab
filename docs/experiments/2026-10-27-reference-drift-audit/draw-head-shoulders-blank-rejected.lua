local function line(key,points)
 for i=1,#points-1 do
  local a,b=point(points[i]),point(points[i+1]);local x,y=a[1],a[2]
  local dx,dy=math.abs(b[1]-x),-math.abs(b[2]-y)
  local sx,sy=x<b[1] and 1 or -1,y<b[2] and 1 or -1
  local err=dx+dy
  while true do
   put(x,y,key);if x==b[1] and y==b[2] then break end
   local e=2*err;if e>=dy then err=err+dy;x=x+sx end;if e<=dx then err=err+dx;y=y+sy end
  end
 end
end
local function poly(key,source)
 local points={};local ymin,ymax=112,0
 for _,p in ipairs(source) do local q=point(p);points[#points+1]=q;ymin=math.min(ymin,q[2]);ymax=math.max(ymax,q[2]) end
 for y=ymin,ymax do
  local hits={}
  for i=1,#points do
   local a,b=points[i],points[i%#points+1]
   if (a[2]<=y+.5 and b[2]>y+.5) or (b[2]<=y+.5 and a[2]>y+.5) then
    hits[#hits+1]=a[1]+(y+.5-a[2])*(b[1]-a[1])/(b[2]-a[2])
   end
  end
  table.sort(hits)
  for i=1,#hits-1,2 do for x=math.ceil(hits[i]-.5),math.floor(hits[i+1]-.5) do put(x,y,key) end end
 end
end
