local function put(x,y,key) if x>=0 and x<120 and y>=0 and y<112 then image:drawPixel(x,y,values[key]) end end
local function line(key,points)
 for i=1,#points-1 do
  local a,b=pt(points[i]),pt(points[i+1]);local x,y=a[1],a[2]
  local dx,dy=math.abs(b[1]-x),-math.abs(b[2]-y)
  local sx,sy=x<b[1] and 1 or -1,y<b[2] and 1 or -1;local err=dx+dy
  while true do
   put(x,y,key);if x==b[1] and y==b[2] then break end
   local e=2*err;if e>=dy then err=err+dy;x=x+sx end;if e<=dx then err=err+dx;y=y+sy end
  end
 end
end
local function poly(key,points)
 local q={};local ymin,ymax=112,0
 for _,p in ipairs(points) do local t=pt(p);q[#q+1]=t;ymin=math.min(ymin,t[2]);ymax=math.max(ymax,t[2]) end
 for y=ymin,ymax do
  local xs={}
  for i=1,#q do local a,b=q[i],q[i%#q+1]
   if (a[2]<=y+.5 and b[2]>y+.5) or (b[2]<=y+.5 and a[2]>y+.5) then xs[#xs+1]=a[1]+(y+.5-a[2])*(b[1]-a[1])/(b[2]-a[2]) end
  end
  table.sort(xs);for i=1,#xs-1,2 do for x=math.ceil(xs[i]-.5),math.floor(xs[i+1]-.5) do put(x,y,key) end end
 end
end
